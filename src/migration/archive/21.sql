UPDATE choices c
   SET sort_order = array_position(o.texts, c.text)
  FROM questions q
       JOIN choice_order o
         ON o.exam_type = q.exam_type
        AND o.qtext = q.text
        AND NOT EXISTS (
                SELECT 1
                  FROM choices other
                 WHERE other.question_id = q.id
                   AND NOT (other.text = ANY (o.texts))
            )
 WHERE c.question_id = q.id;

UPDATE memorization_choices mc
   SET sort_order = array_position(o.texts, mc.text)
  FROM memorization m
       JOIN choice_order o
         ON o.exam_type = m.exam_type
        AND o.qtext = m.text
        AND NOT EXISTS (
                SELECT 1
                  FROM memorization_choices other
                 WHERE other.memorization_id = m.id
                   AND NOT (other.text = ANY (o.texts))
            )
 WHERE mc.memorization_id = m.id;

-- Anything the seed could not account for still needs a fixed order, or it
-- would keep shuffling. Alphabetical is arbitrary but it is the same every
-- time, which is the property that was missing.
UPDATE choices c
   SET sort_order = ranked.rn
  FROM (
        SELECT id,
               row_number() OVER (PARTITION BY question_id ORDER BY text) AS rn
          FROM choices
         WHERE sort_order IS NULL
       ) ranked
 WHERE c.id = ranked.id;

UPDATE memorization_choices mc
   SET sort_order = ranked.rn
  FROM (
        SELECT id,
               row_number() OVER (PARTITION BY memorization_id ORDER BY text) AS rn
          FROM memorization_choices
         WHERE sort_order IS NULL
       ) ranked
 WHERE mc.id = ranked.id;

ALTER TABLE choices ALTER COLUMN sort_order SET NOT NULL;
ALTER TABLE memorization_choices ALTER COLUMN sort_order SET NOT NULL;

COMMIT;

-- Every question should now have its options numbered 1..n with no repeats.
-- Both counts are expected to come back zero.
SELECT (
        SELECT COUNT(*)
          FROM (
                SELECT question_id
                  FROM choices
                 GROUP BY question_id
                HAVING COUNT(DISTINCT sort_order) <> COUNT(*)
               ) x
       ) AS questions_with_clashing_order,
       (
        SELECT COUNT(*)
          FROM (
                SELECT memorization_id
                  FROM memorization_choices
                 GROUP BY memorization_id
                HAVING COUNT(DISTINCT sort_order) <> COUNT(*)
               ) y
       ) AS memorization_with_clashing_order;
