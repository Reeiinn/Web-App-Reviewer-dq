-- Choices are shown in the order the source exam prints them.
--
-- The a/b/c/d order was lost the moment the seed ran. choices has no column
-- for it and its primary key is a random uuid, so /api/questions got its
-- options back from json_agg in whatever order the planner produced - which
-- is not stable between requests. The letters the UI stamps on the options
-- therefore moved around between page loads, and a reviewee checking their
-- answers against the printed reviewer saw mismatches that were not real.
--
-- The order still exists in the seed files, which list every question's
-- options exactly as the exam prints them. This file carries that order over
-- as sort_order, one array per question, matched by option text.
--
-- Run AFTER 20.sql: that file restores Traditional #32's wording, and the
-- questions here are matched on their text.
